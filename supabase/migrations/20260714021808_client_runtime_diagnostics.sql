create table if not exists public.client_runtime_diagnostics (
  id bigint generated by default as identity primary key,
  incident_id text not null unique check (char_length(incident_id) <= 80),
  event_type text not null check (char_length(event_type) <= 80),
  severity text not null default 'error'
    check (severity in ('info', 'warning', 'error', 'fatal')),
  message text not null,
  stack text,
  digest text,
  pathname text,
  deployment_id text,
  device_id text,
  user_id uuid references auth.users(id) on delete set null,
  user_agent text,
  occurred_at timestamptz not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists client_runtime_diagnostics_created_at_idx
  on public.client_runtime_diagnostics (created_at desc);

create index if not exists client_runtime_diagnostics_device_created_idx
  on public.client_runtime_diagnostics (device_id, created_at desc);

create index if not exists client_runtime_diagnostics_deployment_created_idx
  on public.client_runtime_diagnostics (deployment_id, created_at desc);

alter table public.client_runtime_diagnostics enable row level security;

revoke all on table public.client_runtime_diagnostics from anon, authenticated;
